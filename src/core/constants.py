"""
视线估计和眼睑检测的可调参数常量

该模块定义了视线估计算法和眼睑角度计算所需的所有可调参数。
"""


class GazeConstants:
    """视线估计相关常量"""

    # 眼球中心估算参数
    # 眼球中心相对于内外眼角中点的Z轴向后偏移（归一化坐标）
    # 值越大，估算的眼球中心越靠近头部内部
    EYE_CENTER_Z_OFFSET = 0.03

    # 视线角度范围（度）
    MAX_YAW = 50.0    # 最大水平偏转角（左右看）
    MAX_PITCH = 50.0  # 最大垂直偏转角（上下看）


class EyelidConstants:
    """眼睑角度相关常量

    眼睑角度定义：从眼球中心指向眼睑的向量与垂直轴的夹角
    - 0度 = 垂直向上/向下（眼睑完全张开）
    - 90度 = 水平（眼睑覆盖眼球中心）
    """

    # 上眼睑角度范围（度）
    UPPER_EYELID_OPEN = 10.0    # 上眼睑完全睁开时的角度
    UPPER_EYELID_CLOSED = 90.0  # 上眼睑覆盖眼球上半时的角度

    # 下眼睑角度范围（度）
    LOWER_EYELID_OPEN = 10.0    # 下眼睑完全睁开时的角度
    LOWER_EYELID_CLOSED = 90.0  # 下眼睑覆盖眼球下半时的角度
